function setTheme(theme) {
  document.documentElement.setAttribute("data-theme", theme);
  document.body.setAttribute("data-bs-theme", theme);
  localStorage.setItem("theme", theme);
}

function setLanguage(lang) {
  document.documentElement.lang = lang;
  const dictionary = i18n[lang] || i18n.en;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });
  updateFurnitureCategoryLabels(lang);
  updateSummaryLabels(lang);
}

function updateRangeValue(input) {
  const display = document.querySelector(`[data-range-value-for="${input.id}"]`);
  if (display) {
    display.textContent = `${input.value}%`;
  }
}

function createFurnitureRow(item = { name: "", category: "kitchen", value: 0 }) {
  const row = document.createElement("tr");

  const nameCell = document.createElement("td");
  const nameInput = document.createElement("input");
  nameInput.type = "text";
  nameInput.className = "form-control form-control-sm";
  nameInput.value = item.name;
  nameCell.appendChild(nameInput);

  const categoryCell = document.createElement("td");
  const categorySelect = document.createElement("select");
  categorySelect.className = "form-select form-select-sm";
  categorySelect.innerHTML = `
    <option value="kitchen">${i18n[languageSelect.value].categoryKitchen}</option>
    <option value="appliances">${i18n[languageSelect.value].categoryAppliances}</option>
    <option value="furniture">${i18n[languageSelect.value].categoryFurniture}</option>
  `;
  categorySelect.value = item.category;
  categoryCell.appendChild(categorySelect);

  const valueCell = document.createElement("td");
  const valueInput = document.createElement("input");
  valueInput.type = "number";
  valueInput.className = "form-control form-control-sm";
  valueInput.value = item.value;
  valueCell.appendChild(valueInput);

  const deleteCell = document.createElement("td");
  const deleteButton = document.createElement("button");
  deleteButton.type = "button";
  deleteButton.className = "btn btn-outline-danger btn-sm";
  deleteButton.textContent = "×";
  deleteButton.addEventListener("click", () => row.remove());
  deleteCell.appendChild(deleteButton);

  row.append(nameCell, categoryCell, valueCell, deleteCell);
  furnitureTableBody.appendChild(row);
}

function updateFurnitureCategoryLabels(lang) {
  furnitureTableBody.querySelectorAll("select").forEach((select) => {
    const value = select.value;
    select.innerHTML = `
      <option value="kitchen">${i18n[lang].categoryKitchen}</option>
      <option value="appliances">${i18n[lang].categoryAppliances}</option>
      <option value="furniture">${i18n[lang].categoryFurniture}</option>
    `;
    select.value = value;
  });
}

function collectFurnitureItems() {
  const rows = furnitureTableBody.querySelectorAll("tr");
  return Array.from(rows).map((row) => {
    const [nameInput, categorySelect, valueInput] = row.querySelectorAll("input, select");
    return {
      name: nameInput.value,
      category: categorySelect.value,
      value: Number(valueInput.value || 0),
    };
  });
}

function getFormValue(id) {
  const input = document.getElementById(id);
  if (!input) {
    return 0;
  }
  return input.type === "checkbox" ? input.checked : input.value;
}

function getFurnishingOption() {
  const selected = document.querySelector("input[name='furnishing_option']:checked");
  return selected ? selected.value : "unfurnished";
}

function updateSummaryLabels(lang) {
  const list = document.getElementById("result_stats");
  list.querySelectorAll("li").forEach((item) => {
    const labelKey = item.getAttribute("data-label-key");
    if (labelKey) {
      item.querySelector("span").textContent = i18n[lang][labelKey];
    }
  });
}

function formatValue(value, format, locale) {
  if (value === null || value === undefined) {
    return "-";
  }
  if (format === "percent") {
    return `${Number(value).toFixed(2)}%`;
  }
  if (format === "currency") {
    return new Intl.NumberFormat(locale, {
      style: "currency",
      currency: "EUR",
      maximumFractionDigits: 2,
    }).format(Number(value));
  }
  return value;
}

function renderSummary(summary) {
  const list = document.getElementById("result_stats");
  list.innerHTML = "";
  const locale = languageSelect.value === "de" ? "de-DE" : languageSelect.value === "zh" ? "zh-CN" : "en-US";

  const wealthDelta = summary["Net Wealth With Property"] - summary["Net Wealth Without Property"];
  const mergedSummary = { ...summary, "Wealth Delta": wealthDelta };

  summaryConfig.forEach((config) => {
    const listItem = document.createElement("li");
    listItem.className = "list-group-item d-flex justify-content-between align-items-start";
    listItem.setAttribute("data-label-key", config.label);

    const label = document.createElement("span");
    label.textContent = i18n[languageSelect.value][config.label];
    const value = document.createElement("strong");
    value.textContent = formatValue(mergedSummary[config.key], config.format, locale);

    listItem.append(label, value);
    list.appendChild(listItem);
  });
}

async function calculateFurniture() {
  const payload = {
    method: getFormValue("depreciation_method"),
    lifespans: {
      kitchen: Number(getFormValue("lifespan_kitchen")),
      appliances: Number(getFormValue("lifespan_appliances")),
      furniture: Number(getFormValue("lifespan_furniture")),
    },
    items: collectFurnitureItems(),
  };

  const response = await fetch("/api/furniture-depreciation", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
  });
  const data = await response.json();
  const locale = languageSelect.value === "de" ? "de-DE" : languageSelect.value === "zh" ? "zh-CN" : "en-US";

  document.getElementById("furniture_cost").textContent = new Intl.NumberFormat(locale, {
    style: "currency",
    currency: "EUR",
  }).format(data.total_cost);
  document.getElementById("furniture_depreciation").textContent = new Intl.NumberFormat(locale, {
    style: "currency",
    currency: "EUR",
  }).format(data.depreciation);
}

let lastFigure = null;

function applyPlotlyTheme(figure) {
  const theme = document.documentElement.getAttribute("data-theme") || "light";
  const layout = { ...(figure.layout || {}) };
  if (theme === "dark") {
    layout.template = "plotly_dark";
    layout.paper_bgcolor = "rgba(0,0,0,0)";
    layout.plot_bgcolor = "rgba(0,0,0,0)";
    layout.font = { ...(layout.font || {}), color: "#f9fafb" };
  } else {
    layout.template = "plotly_white";
    layout.paper_bgcolor = "rgba(0,0,0,0)";
    layout.plot_bgcolor = "rgba(0,0,0,0)";
    layout.font = { ...(layout.font || {}), color: "#101828" };
  }
  return { ...figure, layout };
}

